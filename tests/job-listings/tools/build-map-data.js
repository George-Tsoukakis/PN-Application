/* Generates job-listings/modules/listings/jbli-map-data.php: the static map of
   Greece for the [listings] map (9.9.62). DEV-ONLY, not shipped.

   Needs (outside the repo lockfile):  npm i --no-save world-atlas@2 topojson-client@3 d3-geo@3
   Run from this folder:               node build-map-data.js
   Map data: Natural Earth via world-atlas (public domain). */
'use strict';
const fs = require('fs');
const path = require('path');
const topo = require('topojson-client');
const d3 = require('d3-geo');

const load = (f) => JSON.parse(fs.readFileSync(require.resolve('world-atlas/' + f)));
const hi = load('countries-10m.json');
const lo = load('countries-50m.json');
const feat = (w, id) => topo.feature(w, w.objects.countries).features.find((f) => f.id === id);

const W = 760, H = 620;
const proj = d3.geoMercator().fitExtent([[16, 16], [W - 16, H - 16]], { type: 'MultiPoint', coordinates: [[19.3, 34.7], [29.7, 34.7], [29.7, 41.8], [19.3, 41.8]] });
const clip = d3.geoPath(proj).digits(1);

/* Seat / centre of each of the plugin's 51 νομοί (lon, lat). Keys = term names seeded by jbli_seed_nomoi(). */
const NOMOI = {
	'Αττική': [23.73, 37.98], 'Αιτωλία & Ακαρνανία': [21.38, 38.62], 'Αργολίδα': [22.80, 37.57], 'Αρκαδία': [22.37, 37.51],
	'Άρτα': [20.99, 39.16], 'Αχαΐα': [21.73, 38.25], 'Βοιωτία': [23.00, 38.40], 'Γρεβενά': [21.43, 40.08], 'Δράμα': [24.15, 41.15],
	'Δωδεκάνησος': [28.22, 36.43], 'Έβρος': [26.05, 41.05], 'Ευβοία': [23.75, 38.55], 'Ευρυτανία': [21.79, 38.91], 'Ζάκυνθος': [20.90, 37.78],
	'Ηλεία': [21.43, 37.67], 'Ημαθία': [22.20, 40.52], 'Ηράκλειο': [25.13, 35.34], 'Θεσπρωτία': [20.30, 39.50], 'Θεσσαλονίκη': [22.94, 40.64],
	'Ιωάννινα': [20.85, 39.66], 'Καβάλα': [24.41, 40.94], 'Καρδίτσα': [21.92, 39.36], 'Καστοριά': [21.27, 40.52], 'Κέρκυρα': [19.92, 39.62],
	'Κεφαλληνία': [20.49, 38.18], 'Κιλκίς': [22.87, 41.00], 'Κοζάνη': [21.79, 40.30], 'Κορινθία': [22.93, 37.94], 'Κυκλάδες': [25.15, 37.10],
	'Λακωνία': [22.43, 37.07], 'Λάρισα': [22.42, 39.64], 'Λασίθι': [25.72, 35.19], 'Λέσβος': [26.40, 39.20], 'Λευκάδα': [20.65, 38.75],
	'Μαγνησία': [22.94, 39.36], 'Μεσσηνία': [22.11, 37.04], 'Ξάνθη': [24.88, 41.14], 'Πέλλα': [22.10, 40.80], 'Πιερία': [22.50, 40.27],
	'Πρέβεζα': [20.75, 38.96], 'Ρέθυμνο': [24.48, 35.37], 'Ροδόπη': [25.41, 41.12], 'Σάμος': [26.85, 37.75], 'Σέρρες': [23.55, 41.09],
	'Τρίκαλα': [21.77, 39.55], 'Φθιώτιδα': [22.43, 38.90], 'Φλώρινα': [21.41, 40.78], 'Φωκίδα': [22.41, 38.53], 'Χαλκιδική': [23.45, 40.30],
	'Χανιά': [24.02, 35.51], 'Χίος': [26.13, 38.37],
};

const neighbours = ['008', '807', '100', '792', '196'].map((id) => clip(feat(lo, id))).filter(Boolean).join('');
const greece = clip(feat(hi, '300'));
const pins = Object.entries(NOMOI).map(([n, c]) => {
	const [x, y] = proj(c);
	return `\t\t'${n}' => array( ${x.toFixed(1)}, ${y.toFixed(1)} ),`;
}).join('\n');

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">`
	+ `<rect width="${W}" height="${H}" fill="#eaf4fb"/>`
	+ `<path d="${neighbours}" fill="#f1f3f2" stroke="#d6dbd9" stroke-width="1"/>`
	+ `<path d="${greece}" fill="#ffffff" stroke="#9fd8bf" stroke-width="1.2"/></svg>\n`;

const php = `<?php
/**
 * Pin positions for the [listings] map section (9.9.62).
 *
 * GENERATED by tests/job-listings/tools/build-map-data.js — do not edit by
 * hand. The outline itself is modules/listings/img/jbli-greece.svg
 * (Natural Earth, public domain, via world-atlas).
 *
 * @package JobListings
 * @since   9.9.62
 */

defined( 'ABSPATH' ) || exit;

return array(
	'width'  => ${W},
	'height' => ${H},
	/* νομός name => array( x, y ) in the map's viewBox. */
	'pins'   => array(
${pins}
	),
);
`;
const dir = path.resolve(__dirname, '../../../job-listings/modules/listings');
fs.mkdirSync(path.join(dir, 'img'), { recursive: true });
fs.writeFileSync(path.join(dir, 'img/jbli-greece.svg'), svg);
fs.writeFileSync(path.join(dir, 'jbli-map-data.php'), php);
console.log('svg', (svg.length / 1024).toFixed(1) + ' KB', 'php', (php.length / 1024).toFixed(1) + ' KB');
